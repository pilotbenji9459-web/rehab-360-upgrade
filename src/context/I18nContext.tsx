const validLanguageCodes = new Set<string>(SUPPORTED_LANGUAGES.map((language) => language.code));

interface I18nContextType {
  language: LanguageCode;
  locale: LanguageCode;
  setLanguage: (lang: LanguageCode) => void;
  setLocale: (lang: LanguageCode) => void;
  t: (key: string, fallback?: string) => string;
}

const I18nContext = createContext<I18nContextType>({
  language: 'en',
  locale: 'en',
  setLanguage: () => {},
  setLocale: () => {},
  t: (key, fallback) => fallback || english[key] || key,
});

export const I18nProvider: React.FC<{ children: React.ReactNode }> = ({ children }) => {
  const [language, setLanguageState] = useState<LanguageCode>(() => {
    try {
      const stored = localStorage.getItem('rehabpath360:lang');
      if (stored && validLanguageCodes.has(stored)) return stored as LanguageCode;
    } catch {
      // Storage can be unavailable in private browsing contexts.
    }
    return 'en';
  });

  useEffect(() => {
    document.documentElement.lang = LANGUAGE_LOCALES[language];
    document.documentElement.dir = 'ltr';
    document.documentElement.dataset.language = language;
    try {
      localStorage.setItem('rehabpath360:lang', language);
    } catch {
      // The language still works for the current session.
    }
  }, [language]);

  const setLanguage = (nextLanguage: LanguageCode) => {
    if (validLanguageCodes.has(nextLanguage)) setLanguageState(nextLanguage);
    else setLanguageState('en');
  };

  const t = (key: string, fallback?: string): string => {
    return interfaceCopy[language][key] || translations[language][key] || english[key] || fallback || key;
  };

  return (
    <I18nContext.Provider
      value={{
        language,
        locale: language,
        setLanguage,
        setLocale: setLanguage,
        t,
      }}
    >
      {children}
    </I18nContext.Provider>
  );
};

export const useI18n = () => useContext(I18nContext);
